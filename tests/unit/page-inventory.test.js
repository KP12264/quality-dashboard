// Legacy Page Inventory (Phase 7): every HTML page in the site, what it loads and whether it can
// write to Firestore. A page that can write must load the sign-in module (js/qd-auth.js) — or be a
// retired copy (js/retired-page.js, which stops Firebase from starting). Scrap is saved only on pages
// that load the ledger. Writes docs/phase7/generated/legacy-page-inventory.md.
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '../..');

const WRITERS = { 'scrap-adapter.js': 'scrapLogs', 'improvement-adapter.js': 'improvements', 'target-adapter.js': 'targetMaster', 'scrap-model-mapping-adapter.js': 'scrapModelMappings', 'scrap-plan-adapter.js': 'scrapWeeklyPlans', 'admin-page.js': 'qdUsers/targetMaster', 'scrap-import.js': 'scrapLogs (Excel)', 'scrap-entry-page.js': 'scrapLogs (form)', 'scrap-detail-page.js': 'scrapLogs (edit/delete)', 'improvement-page.js': 'improvements', 'plan-tracking-page.js': 'scrapWeeklyPlans', 'ops-console.js': 'scrapSlots / qdConfig / qdOpsLog (Operations, admin)' };
const pages = fs.readdirSync(ROOT).filter(f => f.endsWith('.html')).concat(fs.readdirSync(path.join(ROOT, 'js')).filter(f => f.endsWith('.html')).map(f => 'js/' + f));
function inspect(p) {
  const html = fs.readFileSync(path.join(ROOT, p), 'utf8');
  const scripts = [...html.matchAll(/<script[^>]*src="([^"]+)"/g)].map(m => path.basename(m[1].split('?')[0]));
  const inline = [...html.matchAll(/<script(?![^>]*src)[^>]*>([\s\S]*?)<\/script>/g)].map(m => m[1]).join('\n');
  const writes = Object.keys(WRITERS).filter(s => scripts.includes(s)).map(s => WRITERS[s]);
  const linked = pages.filter(o => o !== p && fs.readFileSync(path.join(ROOT, o), 'utf8').includes(`href="${p}"`));
  return {
    page: p, title: (html.match(/<title>([^<]*)/) || [])[1] || '', retired: scripts[0] === 'retired-page.js',
    firebase: scripts.includes('firebase-init.js'), auth: scripts.includes('qd-auth.js'), ledger: scripts.includes('scrap-ledger.js'),
    writes, inlineWrites: /\.(add|set|update|delete)\(|batch\(\)/.test(inline), linked
  };
}
const rows = pages.map(inspect);

test('every page that can write loads sign-in, or is retired (never connects)', () => {
  for (const r of rows) if (r.writes.length && r.firebase) assert.ok(r.auth || r.retired, `${r.page} can write (${r.writes.join(', ')}) without sign-in`);
});
test('scrap is saved only on pages that load the ledger', () => {
  for (const r of rows) {
    const savesScrap = r.writes.some(w => /^scrapLogs \(/.test(w));
    if (savesScrap && !r.retired) assert.ok(r.ledger, `${r.page} saves scrap without the ledger`);
  }
});
test('no inline script writes to Firestore', () => {
  for (const r of rows) assert.equal(r.inlineWrites, false, r.page);
});
test('the three old copies are retired and point to the current pages', () => {
  const retired = Object.fromEntries(rows.filter(r => r.retired).map(r => [r.page, fs.readFileSync(path.join(ROOT, r.page), 'utf8').match(/data-to="([^"]+)"/)[1]]));
  assert.deepEqual(retired, { 'dashboard.html': 'scrap-entry.html', 'dashboard-classic.html': 'index.html', 'js/scrap-entry.html': '../scrap-entry.html' });
});
test.after(() => {
  const yes = b => (b ? 'yes' : '—');
  const md = ['# Legacy Page Inventory (generated)', '', 'Generated by `tests/unit/page-inventory.test.js` from the HTML files in the repository.', '',
    '| Page | Title | Retired | Firebase | Sign-in | Ledger | Loads code that writes | Linked from |', '|---|---|---|---|---|---|---|---|',
    ...rows.map(r => `| \`${r.page}\` | ${r.title.replace(/&amp;/g, '&')} | ${r.retired ? '**retired**' : '—'} | ${yes(r.firebase)} | ${yes(r.auth)} | ${yes(r.ledger)} | ${r.writes.join(', ') || '—'} | ${r.linked.map(x => '`' + x + '`').join(' ') || 'not linked'} |`)].join('\n');
  fs.mkdirSync(path.join(ROOT, 'docs/phase7/generated'), { recursive: true });
  fs.writeFileSync(path.join(ROOT, 'docs/phase7/generated/legacy-page-inventory.md'), md + '\n');
});
