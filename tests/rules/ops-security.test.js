// Operations security (Phase 9) — EMULATOR ONLY. Direct Firestore SDK calls (no UI) by every
// identity against every go-live write; forged / expired / borrowed audit records; concurrent
// operations. Writes docs/phase9/generated/ops-security-matrix.md.
const { describe, it, before, after } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('fs');
const path = require('path');
const { initializeTestEnvironment } = require('@firebase/rules-unit-testing');
const { doc, getDoc, getDocs, setDoc, addDoc, updateDoc, deleteDoc, writeBatch, collection, serverTimestamp, Timestamp } = require('firebase/firestore');
const Ledger = require('../../js/scrap-ledger.js');
const SC = require('../../js/shift-close.js');
const MB = require('../../tools/migration/ledger-baseline.js');
const OPS = require('../../tools/ops/bridge-ops.js');
const { op } = require('../support/ops-helper.js');
const { compatDb } = require('../support/compat-shim.js');

const ROOT = path.join(__dirname, '../..');
const E = c => `${c.toLowerCase()}@prodv2.local`;
const pad = n => String(n).padStart(2, '0');
const bkk = n => { const d = new Date(Date.now() + 7 * 3600000 - n * 86400000); return `${d.getUTCFullYear()}-${pad(d.getUTCMonth() + 1)}-${pad(d.getUTCDate())}`; };
const DAY = bkk(3);
const IDS = { anonymous: null, viewer: 'viewer', leader: 'leaderA', admin: 'admin', admin2: 'admin2', pv2Writer: 'pv2w' };
let env;
const matrix = {};   // operation -> identity -> 'ALLOW' | 'deny'
const notes = [];
const fsOf = c => c ? env.authenticatedContext('uid-' + c, { email: E(c) }).firestore() : env.unauthenticatedContext().firestore();
const actor = c => { const db = compatDb(fsOf(c)); return { db, opts: { email: E(c), serverTimestamp } }; };
async function raw(fn) { let o; await env.withSecurityRulesDisabled(async ctx => { o = await fn(ctx.firestore()); }); return o; }
const row = (o = {}) => Object.assign({ date: DAY, line: 'A', shift: 'DAY', model: 'M', defectType: 'Dent', scrapQty: 1, remark: '', createdAt: 1 }, o);
const ok = p => p.then(() => 'ALLOW', () => 'deny');

// A stray record so that reconcile has something to do: slot A Day has 1 ledger log + 1 written around it.
async function freshProblemSlot(date) {
  const A = actor('admin');
  await Ledger.applyOps(A.db, [{ op: 'create', ref: A.db.collection('scrapLogs').doc(), data: row({ date }) }], A.opts);
  await raw(async db => { await setDoc(doc(db, 'scrapLogs', 'stray_' + date), row({ date, scrapQty: 7 })); });
  return `${date}_A_DAY`;
}
async function seedOp(by, action, ageHours) {
  return raw(async db => { const ref = doc(collection(db, 'qdOpsLog')); await setDoc(ref, { action, stage: 'START', projectId: 'demo', database: '(default)', approvalRef: 'X-1', reason: 'seeded', summary: '', at: Timestamp.fromMillis(Date.now() - ageHours * 3600000), by: E(by) }); return ref.id; });
}

before(async () => {
  env = await initializeTestEnvironment({ projectId: 'demo-quality-dashboard', firestore: { rules: fs.readFileSync(path.join(ROOT, 'emulator/firestore.rules'), 'utf8'), host: '127.0.0.1', port: 8080 } });
  await env.clearFirestore();
  await raw(async db => {
    const u = (role, slots) => ({ role, active: true, displayName: role, slots, updatedAt: 1, updatedBy: E('admin') });
    await setDoc(doc(db, 'qdUsers', E('admin')), u('admin', []));
    await setDoc(doc(db, 'qdUsers', E('admin2')), u('admin', []));
    await setDoc(doc(db, 'qdUsers', E('leaderA')), u('leader', ['A_DAY']));
    await setDoc(doc(db, 'qdUsers', E('viewer')), u('viewer', []));
    await setDoc(doc(db, 'prodV2_authorizedUsers', E('pv2w')), { active: true });
  });
});
after(async () => {
  const ops = Object.keys(matrix), ids = Object.keys(IDS);
  const md = ['# Operations Security Matrix (generated)', '', 'Generated by `tests/rules/ops-security.test.js`: direct Firestore SDK calls (no UI, client lock irrelevant) against the candidate rules in the Emulator. ✓ = accepted, · = refused.', '',
    '| Operation | ' + ids.join(' | ') + ' |', '|---|' + ids.map(() => '---').join('|') + '|',
    ...ops.map(o => `| ${o} | ` + ids.map(i => matrix[o][i] === undefined ? '—' : matrix[o][i] === 'ALLOW' ? '✓' : '·').join(' | ') + ' |'), '', '## Notes', '', ...notes.map(n => '- ' + n)].join('\n');
  fs.mkdirSync(path.join(ROOT, 'docs/phase9/generated'), { recursive: true });
  fs.writeFileSync(path.join(ROOT, 'docs/phase9/generated/ops-security-matrix.md'), md + '\n');
  if (env) await env.cleanup();
});

describe('direct SDK calls by every identity', () => {
  it('open an operation run (qdOpsLog START): admins only; fields must be true', async () => {
    const r = matrix['Open a run (qdOpsLog START, own name, server time)'] = {};
    for (const [k, c] of Object.entries(IDS)) r[k] = await ok(addDoc(collection(fsOf(c), 'qdOpsLog'), { action: 'RECONCILE', stage: 'START', projectId: 'p', database: '(default)', approvalRef: 'X-1', reason: 'test', summary: '', at: serverTimestamp(), by: c ? E(c) : 'x' }));
    assert.deepEqual(Object.keys(r).filter(k => r[k] === 'ALLOW').sort(), ['admin', 'admin2']);
    const f = matrix['Forge qdOpsLog (other admin\'s name / client time / bad action)'] = {};
    const A = fsOf('admin');
    const bad = [{ by: E('admin2'), at: serverTimestamp() }, { by: E('admin'), at: Timestamp.now() }, { by: E('admin'), at: serverTimestamp(), action: 'DROP_ALL' }];
    let any = 'deny';
    for (const b of bad) if (await ok(addDoc(collection(A, 'qdOpsLog'), Object.assign({ action: 'RECONCILE', stage: 'START', projectId: 'p', database: '(default)', approvalRef: 'X-1', reason: 'test', summary: '' }, b))) === 'ALLOW') any = 'ALLOW';
    f.admin = any;
    assert.equal(any, 'deny');
  });
  it('change or delete the audit log: nobody', async () => {
    const id = await seedOp('admin', 'RECONCILE', 0);
    const r = matrix['Update / delete a qdOpsLog record'] = {};
    for (const [k, c] of Object.entries(IDS)) r[k] = (await ok(updateDoc(doc(fsOf(c), 'qdOpsLog', id), { approvalRef: 'changed' }))) === 'ALLOW' || (await ok(deleteDoc(doc(fsOf(c), 'qdOpsLog', id)))) === 'ALLOW' ? 'ALLOW' : 'deny';
    assert.ok(Object.values(r).every(v => v === 'deny'));
    const rd = matrix['Read the audit log'] = {};
    for (const [k, c] of Object.entries(IDS)) rd[k] = await ok(getDocs(collection(fsOf(c), 'qdOpsLog')));
    assert.deepEqual(Object.keys(rd).filter(k => rd[k] === 'ALLOW').sort(), ['admin', 'admin2']);
  });
  it('RECONCILE: only with the caller\'s own, matching, recent run', async () => {
    const r = matrix['Reconcile a slot with an own valid run'] = {};
    for (const [k, c] of Object.entries(IDS)) {
      const slot = await freshProblemSlot(bkk(10 + Object.keys(IDS).indexOf(k)));
      const a = actor(c || 'nobody');
      const opId = c && c.startsWith('admin') ? (await op(a, 'RECONCILE')).opId : await seedOp('admin', 'RECONCILE', 0);   // non-admins try to borrow an admin's run
      r[k] = c ? await ok(OPS.reconcileSlot(a.db, slot, 'test reconcile', Object.assign({}, a.opts, { opId }))) : 'deny';
    }
    assert.deepEqual(Object.keys(r).filter(k => r[k] === 'ALLOW').sort(), ['admin', 'admin2']);
    const slot = await freshProblemSlot(bkk(20));
    const A = actor('admin');
    const variants = {
      'Reconcile without a run': undefined,
      'Reconcile with another admin\'s run': await seedOp('admin2', 'RECONCILE', 0),
      'Reconcile with a run for another action': await seedOp('admin', 'BASELINE_APPLY', 0),
      'Reconcile with a run older than 12 h': await seedOp('admin', 'RECONCILE', 13)
    };
    for (const [name, opId] of Object.entries(variants)) {
      matrix[name] = { admin: await ok(OPS.reconcileSlot(A.db, slot, 'test reconcile', Object.assign({}, A.opts, { opId }))) };
      assert.equal(matrix[name].admin, 'deny', name);
    }
  });
  it('baseline b1 and baselineComplete: only under the matching run', async () => {
    await raw(async db => { await setDoc(doc(db, 'scrapLogs', 'legacyB'), row({ date: bkk(30), line: 'B' })); });
    const plan = MB.planBaseline([Object.assign({ id: 'legacyB' }, row({ date: bkk(30), line: 'B' }))], []);
    const b = matrix['Baseline a slot (b1) with an own run'] = {}, g = matrix['Set baselineComplete with an own gate run'] = {};
    for (const [k, c] of Object.entries(IDS)) {
      if (!c) { b[k] = 'deny'; g[k] = 'deny'; continue; }
      const a = actor(c);
      const bo = c.startsWith('admin') ? (await op(a, 'BASELINE_APPLY')).opId : await seedOp('admin', 'BASELINE_APPLY', 0);
      const res = await MB.applyBaseline(a.db, plan, Object.assign({ migrationId: 'm' }, a.opts, { opId: bo }));
      b[k] = res.created.length || res.skipped.length ? 'ALLOW' : 'deny';
      const go = c.startsWith('admin') ? (await op(a, 'BASELINE_GATE')).opId : await seedOp('admin', 'BASELINE_GATE', 0);
      g[k] = await ok(MB.markComplete(a.db, 'm', Object.assign({}, a.opts, { opId: go })));
    }
    assert.deepEqual(Object.keys(b).filter(k => b[k] === 'ALLOW').sort(), ['admin', 'admin2']);
    assert.deepEqual(Object.keys(g).filter(k => g[k] === 'ALLOW').sort(), ['admin', 'admin2']);
    const A = actor('admin');
    matrix['Set baselineComplete without a run'] = { admin: await ok(MB.markComplete(A.db, 'm', A.opts)) };
    matrix['Set baselineComplete with a BASELINE_APPLY run'] = { admin: await ok(MB.markComplete(A.db, 'm', Object.assign({}, A.opts, { opId: (await op(A, 'BASELINE_APPLY')).opId }))) };
    assert.equal(matrix['Set baselineComplete without a run'].admin, 'deny');
    assert.equal(matrix['Set baselineComplete with a BASELINE_APPLY run'].admin, 'deny');
  });
  it('ledger and markers by hand (no ops tool)', async () => {
    const m = matrix['Set an import marker'] = {};
    for (const [k, c] of Object.entries(IDS)) m[k] = c ? await ok(Ledger.markImport(actor(c).db, [row({ date: bkk(40 + Object.keys(IDS).indexOf(k)), line: 'C' })], 'imp-' + k, actor(c).opts).then(r => { if (!r.slots.length) throw new Error('none'); })) : 'deny';
    assert.deepEqual(Object.keys(m).filter(k => m[k] === 'ALLOW').sort(), ['admin', 'admin2']);
    assert.equal(m.leader, 'deny'); assert.equal(m.viewer, 'deny'); assert.equal(m.pv2Writer, 'deny');
    const w = matrix['Write a scrap log around the ledger'] = {};
    for (const [k, c] of Object.entries(IDS)) w[k] = await ok(addDoc(collection(fsOf(c), 'scrapLogs'), row()));
    assert.ok(Object.values(w).every(v => v === 'deny'));
  });
  it('the client lock (QD_OPS_WRITE_ENABLED) is not the boundary: an admin calling the SDK directly is still bound by the run + audit rules', async () => {
    const slot = await freshProblemSlot(bkk(25));
    const A = actor('admin');
    matrix['Admin, direct SDK, no UI, no run'] = { admin: await ok(OPS.reconcileSlot(A.db, slot, 'direct', A.opts)) };
    assert.equal(matrix['Admin, direct SDK, no UI, no run'].admin, 'deny');
    notes.push('`QD_OPS_WRITE_ENABLED` / `?qdOpsWrite=1` only enable the buttons. The boundary is the rules: admin role + an own START record in qdOpsLog (immutable, server time) for the same action within 12 h. A direct SDK call without a run is refused (tested).');
  });
});

describe('concurrent operations', () => {
  it('two admins reconcile the same slot at once: one RECONCILE event, consistent slot', async () => {
    const slot = await freshProblemSlot(bkk(50));
    const A = actor('admin'), B = actor('admin2');
    const [oa, ob] = [await op(A, 'RECONCILE'), await op(B, 'RECONCILE')];
    const res = await Promise.allSettled([OPS.reconcileSlot(A.db, slot, 'concurrent', oa), OPS.reconcileSlot(B.db, slot, 'concurrent', ob)]);
    const evs = await raw(async db => { const o = []; (await getDocs(collection(db, 'scrapSlots', slot, 'events'))).forEach(d => o.push(d.data().type)); return o; });
    const st = await SC.loadSlot(A.db, ...slot.split('_'));
    assert.equal(evs.filter(t => t === 'RECONCILE').length, 1);
    assert.equal(st.slot.liveLogCount, st.logs.length);
    notes.push(`Concurrent reconcile of one slot by two admins: ${res.filter(r => r.status === 'fulfilled').length} succeeded, ${res.filter(r => r.status === 'rejected').length} refused (changed meanwhile); exactly one RECONCILE event.`);
  });
  it('reconcile while a Leader is saving into the same slot: never inconsistent', async () => {
    const slot = await freshProblemSlot(bkk(5));
    const A = actor('admin'), L = actor('leaderA');
    const o = await op(A, 'RECONCILE');
    const res = await Promise.allSettled([OPS.reconcileSlot(A.db, slot, 'concurrent', o), Ledger.applyOps(L.db, [{ op: 'create', ref: L.db.collection('scrapLogs').doc(), data: row({ date: bkk(5) }) }], L.opts)]);
    let st = await SC.loadSlot(A.db, ...slot.split('_'));
    if (st.slot.liveLogCount !== st.logs.length) {   // the reconcile lost its race: run it again (as the runbook says)
      await OPS.reconcileSlot(A.db, slot, 'retry', await op(A, 'RECONCILE'));
      st = await SC.loadSlot(A.db, ...slot.split('_'));
    }
    assert.equal(st.slot.liveLogCount, st.logs.length);
    notes.push(`Reconcile racing a Leader save: reconcile ${res[0].status}, save ${res[1].status}; after (re-)run the slot is consistent.`);
  });
  it('the same baseline applied twice at once: each slot created exactly once', async () => {
    await raw(async db => { for (let i = 0; i < 6; i++) await setDoc(doc(db, 'scrapLogs', 'lg' + i), row({ date: bkk(60), line: 'ABC'[i % 3], shift: i % 2 ? 'NIGHT' : 'DAY' })); });
    const logs = []; (await raw(async db => getDocs(collection(db, 'scrapLogs')))).forEach(d => { if (d.id.startsWith('lg')) logs.push(Object.assign({ id: d.id }, d.data())); });
    const plan = MB.planBaseline(logs, []);
    const A = actor('admin'), B = actor('admin2');
    const [r1, r2] = await Promise.all([MB.applyBaseline(A.db, plan, Object.assign({ migrationId: 'c' }, await op(A, 'BASELINE_APPLY'))), MB.applyBaseline(B.db, plan, Object.assign({ migrationId: 'c' }, await op(B, 'BASELINE_APPLY')))]);
    assert.equal(r1.created.length + r2.created.length, plan.slots.length);
    assert.equal(r1.failed.length + r2.failed.length, 0);
    notes.push(`Same baseline run twice at once: ${r1.created.length} + ${r2.created.length} created = ${plan.slots.length} slots; no duplicates, no failures.`);
  });
});
