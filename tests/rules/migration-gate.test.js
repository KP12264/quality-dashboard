// Migration Gate + Bridge operations (Phase 7) — EMULATOR ONLY, synthetic data.
// Is baselineComplete needed before scrap can be saved? (No: there is no window where saving is
// blocked.) Migration while people are saving, failing half-way, re-run; scrap totals checked
// before/after. Bridge period: old pages writing around the ledger, CONFLICT, audit, admin
// reconcile after the candidate, and a measurable exit condition. Writes
// docs/phase7/generated/migration-gate.md.
const { describe, it, before, after } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('fs');
const path = require('path');
const { initializeTestEnvironment } = require('@firebase/rules-unit-testing');
const { doc, getDocs, setDoc, updateDoc, collection, serverTimestamp } = require('firebase/firestore');
const Ledger = require('../../js/scrap-ledger.js');
const SC = require('../../js/shift-close.js');
const MB = require('../../tools/migration/ledger-baseline.js');
const OPS = require('../../tools/ops/bridge-ops.js');
const { compatDb } = require('../support/compat-shim.js');

const ROOT = path.join(__dirname, '../..');
const RULES = { bridge: 'emulator/firestore.rules.bridge', candidate: 'emulator/firestore.rules' };
const E = c => `${c.toLowerCase()}@prodv2.local`;
const pad = n => String(n).padStart(2, '0');
const bkk = n => { const d = new Date(Date.now() + 7 * 3600000 - n * 86400000); return `${d.getUTCFullYear()}-${pad(d.getUTCMonth() + 1)}-${pad(d.getUTCDate())}`; };
let env;
const report = [];
const row = (date, line, shift, qty = 2) => ({ date, line, shift, model: 'M', defectType: 'Dent', scrapQty: qty, remark: '', createdAt: 1 });
async function useRules(name) { if (env) await env.cleanup(); env = await initializeTestEnvironment({ projectId: 'demo-quality-dashboard', firestore: { rules: fs.readFileSync(path.join(ROOT, RULES[name]), 'utf8'), host: '127.0.0.1', port: 8080 } }); }
const actor = c => { const db = compatDb(env.authenticatedContext('uid-' + c, { email: E(c) }).firestore()); return { db, opts: { email: E(c), serverTimestamp } }; };
const anonDb = () => env.unauthenticatedContext().firestore();
const save = (a, r) => Ledger.applyOps(a.db, [{ op: 'create', ref: a.db.collection('scrapLogs').doc(), data: r }], a.opts);
async function raw(fn) { let o; await env.withSecurityRulesDisabled(async ctx => { o = await fn(ctx.firestore()); }); return o; }
const allLogs = () => raw(async db => { const o = []; (await getDocs(collection(db, 'scrapLogs'))).forEach(d => o.push(Object.assign({ id: d.id }, d.data()))); return o; });
const totals = logs => ({ logs: logs.length, qty: logs.reduce((s, l) => s + l.scrapQty, 0) });
const statusOf = async (a, date, line, shift) => (await SC.loadSlot(a.db, date, line, shift)).info.status;
// A db whose N-th transaction fails (simulates a crash / network loss half-way through the migration).
function failingAt(db, n) { let k = 0; return Object.assign({}, db, { collection: db.collection, runTransaction: fn => (++k === n ? Promise.reject(Object.assign(new Error('simulated failure'), { code: 'unavailable' })) : db.runTransaction(fn)) }); }

before(async () => {
  await useRules('candidate');
  await env.clearFirestore();
  await raw(async db => {
    const u = (role, slots) => ({ role, active: true, displayName: role, slots, updatedAt: 1, updatedBy: E('admin') });
    await setDoc(doc(db, 'qdUsers', E('admin')), u('admin', []));
    await setDoc(doc(db, 'qdUsers', E('leaderA')), u('leader', ['A_DAY', 'A_NIGHT']));
    await setDoc(doc(db, 'qdUsers', E('leaderB')), u('leader', ['B_DAY', 'B_NIGHT']));
    // legacy logs saved before the ledger (sign-in off), 6 days x 6 slots
    let n = 0;
    for (let d = 9; d >= 4; d--) for (const l of ['A', 'B', 'C']) for (const s of ['DAY', 'NIGHT']) for (let i = 0; i < 1 + ((d + i) % 3); i++) await setDoc(doc(db, 'scrapLogs', `old${++n}`), row(bkk(d), l, s, 1 + (n % 5)));
  });
});
after(async () => {
  fs.mkdirSync(path.join(ROOT, 'docs/phase7/generated'), { recursive: true });
  fs.writeFileSync(path.join(ROOT, 'docs/phase7/generated/migration-gate.md'), '# Migration Gate & Bridge Operations (generated)\n\nGenerated by `tests/rules/migration-gate.test.js` (Emulator, synthetic data).\n\n| Scenario | Result |\n|---|---|\n' + report.map(r => `| ${r[0]} | ${r[1]} |`).join('\n') + '\n');
  if (env) await env.cleanup();
});

describe('migration gate (candidate rules)', () => {
  let before0, plan;
  it('scrap can be saved BEFORE the baseline (no write-blocked window): ledger + Excel import', async () => {
    before0 = totals(await allLogs());
    await save(actor('leaderA'), row(bkk(5), 'A', 'DAY', 3));                   // slot with legacy logs: counted lazily
    const A = actor('admin');
    await Ledger.markImport(A.db, [row(bkk(6), 'C', 'NIGHT')], 'imp-pre', A.opts);
    await Ledger.applyOps(A.db, [{ op: 'create', ref: A.db.collection('scrapLogs').doc(), data: row(bkk(6), 'C', 'NIGHT', 4) }], A.opts);
    await Ledger.clearImportMarker(A.db, `${bkk(6)}_C_NIGHT`, A.opts, 'imp-pre');
    assert.equal(await statusOf(A, bkk(5), 'A', 'DAY'), 'PENDING');
    report.push(['Save + Excel import before the baseline', 'PASS — saved; slots counted their old logs lazily (no write-blocked window)']);
  });
  it('migration while Leaders keep saving, failing half-way, then re-run → complete; totals exact', async () => {
    const A = actor('admin');
    const existing = await raw(async db => { const o = []; (await getDocs(collection(db, 'scrapSlots'))).forEach(d => o.push(d.id)); return o; });
    plan = MB.planBaseline(await allLogs(), existing);
    // 1st run fails at the 5th slot
    const r1 = await MB.applyBaseline(failingAt(A.db, 5), plan, Object.assign({ migrationId: 'gate-1' }, A.opts));
    assert.equal(r1.failed.length, 1);
    const gate1 = await MB.completeIfClean(A.db, plan, 'gate-1', A.opts, await allLogs());
    assert.equal(gate1.complete, false);   // the missing slot keeps the gate closed
    // Leaders save during the migration: into a planned slot not yet created, and into a new day
    const L = actor('leaderA'), LB = actor('leaderB');
    const failedSlot = r1.failed[0].slotId;
    const [fd, fl, fs_] = failedSlot.split('_');
    await Promise.all([
      MB.applyBaseline(A.db, plan, Object.assign({ migrationId: 'gate-1' }, A.opts)),
      save(fl === 'A' ? L : fl === 'B' ? LB : A, row(fd, fl, fs_, 5)),
      save(L, row(bkk(2), 'A', 'NIGHT', 1)),
      save(LB, row(bkk(4), 'B', 'DAY', 2))
    ]);
    const again = await MB.applyBaseline(A.db, plan, Object.assign({ migrationId: 'gate-1' }, A.opts));   // re-run: idempotent
    assert.equal(again.created.length, 0); assert.equal(again.failed.length, 0);
    const gate = await MB.completeIfClean(A.db, plan, 'gate-1', A.opts, await allLogs());
    assert.deepEqual(gate, { complete: true }, JSON.stringify(gate));
    const after = totals(await allLogs());
    assert.equal(after.logs, before0.logs + 2 + 3); assert.equal(after.qty, before0.qty + 3 + 4 + 5 + 1 + 2);
    report.push(['Migration fails half-way', `PASS — 1 of ${plan.slots.length} slots failed; gate stayed closed (${gate1.problems.length} problem)`]);
    report.push(['Leaders save during the migration (incl. into a planned slot not yet migrated)', 'PASS — all saved; the slot created by the Leader is skipped by the re-run; gate then opens']);
    report.push(['Migration re-run', 'PASS — idempotent (0 created, 0 failed)']);
    report.push(['Scrap totals before → after', `PASS — ${before0.logs} logs / ${before0.qty} pcs + exactly the 5 saves (${after.logs} / ${after.qty})`]);
  });
  it('after the baseline: saving and Excel import still work (existing and new slots)', async () => {
    const A = actor('admin'), L = actor('leaderA');
    await save(L, row(bkk(5), 'A', 'NIGHT', 2));          // migrated slot (update path)
    await save(L, row(bkk(1), 'A', 'DAY', 2));            // brand-new slot (legacy 0)
    await Ledger.markImport(A.db, [row(bkk(7), 'B', 'DAY'), row(bkk(1), 'C', 'DAY')], 'imp-post', A.opts);
    for (const r of [row(bkk(7), 'B', 'DAY', 3), row(bkk(1), 'C', 'DAY', 3)]) await Ledger.applyOps(A.db, [{ op: 'create', ref: A.db.collection('scrapLogs').doc(), data: r }], A.opts);
    const fin = await Ledger.finishImport(A.db, 'imp-post', [row(bkk(7), 'B', 'DAY'), row(bkk(1), 'C', 'DAY')], [], A.opts);
    assert.equal(fin.cleared.length, 2);
    for (const [d, l, s] of [[bkk(5), 'A', 'NIGHT'], [bkk(1), 'A', 'DAY'], [bkk(7), 'B', 'DAY'], [bkk(1), 'C', 'DAY']]) assert.equal(await statusOf(A, d, l, s), 'PENDING');
    report.push(['Save + Excel import after the baseline', 'PASS — migrated and new slots both work']);
  });
});

describe('bridge period: old pages writing around the ledger', () => {
  const day = bkk(3);
  it('under the bridge, anonymous public write still works (as production today) and goes around the ledger', async () => {
    await useRules('bridge');
    const L = actor('leaderA');
    await save(L, row(day, 'A', 'DAY', 4));
    await SC.closeSlot(L.db, { date: day, line: 'A', shift: 'DAY', state: 'SUBMITTED' }, L.opts);
    await save(L, row(day, 'A', 'NIGHT', 1));                                   // ledger slot, not closed
    const ids = [];
    // the "old site": no sign-in, plain writes
    ids.push((await require('firebase/firestore').addDoc(collection(anonDb(), 'scrapLogs'), row(day, 'A', 'DAY', 9))).id);
    ids.push((await require('firebase/firestore').addDoc(collection(anonDb(), 'scrapLogs'), row(day, 'A', 'NIGHT', 9))).id);
    await updateDoc(doc(anonDb(), 'scrapLogs', ids[0]), { scrapQty: 8 });
    const A = actor('admin');
    assert.equal(await statusOf(A, day, 'A', 'DAY'), 'CONFLICT');
    assert.equal(await statusOf(A, day, 'A', 'NIGHT'), 'CONFLICT');
    const audit = await OPS.bridgeAudit(A.db, { from: day, to: day });
    assert.deepEqual(audit.problems.map(p => p.slotId).sort(), [`${day}_A_DAY`, `${day}_A_NIGHT`]);
    report.push(['Public write during the bridge', 'PASS (as designed) — anonymous create/update accepted, exactly like production today']);
    report.push(['Old page saves into a CLOSED shift', 'PASS — slot becomes CONFLICT, listed by bridgeAudit; never counted silently']);
    report.push(['Old page saves into an open ledger shift', 'PASS — CONFLICT (count mismatch), listed by bridgeAudit']);
  });
  it('after the candidate: old pages refused; Admin reconciles (audited); closed shift must be reconfirmed', async () => {
    await useRules('candidate');
    await assert.rejects(require('firebase/firestore').addDoc(collection(anonDb(), 'scrapLogs'), row(day, 'A', 'DAY', 1)), /permission/i);
    const A = actor('admin'), L = actor('leaderA');
    await assert.rejects(OPS.reconcileSlot(L.db, `${day}_A_DAY`, 'bridge clean-up', L.opts), /permission/i);
    for (const s of ['DAY', 'NIGHT']) await OPS.reconcileSlot(A.db, `${day}_A_${s}`, 'bridge clean-up: records saved by old pages', A.opts);
    assert.equal(await statusOf(A, day, 'A', 'DAY'), 'CHANGED');                // must be reconfirmed
    assert.equal(await statusOf(A, day, 'A', 'NIGHT'), 'PENDING');
    await SC.closeSlot(L.db, { date: day, line: 'A', shift: 'DAY', state: 'SUBMITTED' }, L.opts);
    assert.equal(await statusOf(A, day, 'A', 'DAY'), 'SUBMITTED');
    const ev = await raw(async db => { const o = []; (await getDocs(collection(db, 'scrapSlots', `${day}_A_DAY`, 'events'))).forEach(d => o.push(d.data())); return o; });
    const rec = ev.find(e => e.type === 'RECONCILE');
    assert.equal(rec.before, 1); assert.equal(rec.logIds.length, 2); assert.equal(rec.by, E('admin'));
    const audit = await OPS.bridgeAudit(A.db, { from: bkk(9), to: bkk(0) });
    assert.equal(audit.problems.length, 0, JSON.stringify(audit.problems));
    report.push(['Old page after the candidate', 'PASS — refused']);
    report.push(['Reconcile', 'PASS — Admin only (Leader refused); audited (before/after/ids/fingerprint/reason); closed shift CHANGED → reconfirmed']);
    report.push(['Bridge exit check (bridgeAudit after clean-up)', 'PASS — 0 problems across the whole range']);
  });
  it('a forged reconcile is refused (wrong count, no reason, Leader)', async () => {
    const id = `${day}_A_NIGHT`, db = env.authenticatedContext('uid-admin', { email: E('admin') }).firestore();
    const cur = await raw(async d => (await require('firebase/firestore').getDoc(doc(d, 'scrapSlots', id))).data());
    const { writeBatch } = require('firebase/firestore');
    const attempt = async (count, ev) => { const b = writeBatch(db); const v = cur.logVersion + 1;
      b.update(doc(db, 'scrapSlots', id), { logVersion: v, liveLogCount: count, updatedAt: serverTimestamp(), updatedBy: E('admin') });
      b.set(doc(db, 'scrapSlots', id, 'events', 'v' + v), Object.assign({ type: 'RECONCILE', version: v, at: serverTimestamp(), by: E('admin'), logIds: ['a', 'b'], fingerprint: 'f', scrapQty: 3, before: cur.liveLogCount, reason: 'fix' }, ev));
      b.set(doc(db, 'scrapCloseSummary', day), { date: day, slots: { A_NIGHT: Ledger.publicView(Object.assign({}, cur, { logVersion: v, liveLogCount: count })) }, updatedAt: serverTimestamp() }, { merge: true });
      return b.commit(); };
    await assert.rejects(attempt(5, {}), /permission/i);              // count != listed ids
    await assert.rejects(attempt(2, { reason: '' }), /permission/i);  // no reason
    report.push(['Forged reconcile', 'PASS — refused (count must equal the attested id list; reason required)']);
  });
});
