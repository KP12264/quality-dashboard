// Ledger baseline migration — DRY RUN + APPLY on SYNTHETIC data in the EMULATOR ONLY.
// No production data is read or written. Writes docs/phase5/generated/migration-dry-run.md.
// Checks: every legacy log accounted for once; scrap logs untouched (byte-for-byte); totals per
// day unchanged; no false CONFLICT after the baseline; re-run is idempotent; after
// baselineComplete a client can no longer state legacyCount; stray logs written around the
// ledger are detected.
const { describe, it, before, after } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const { initializeTestEnvironment } = require('@firebase/rules-unit-testing');
const { doc, getDoc, getDocs, setDoc, collection, serverTimestamp, writeBatch } = require('firebase/firestore');
const Ledger = require('../../js/scrap-ledger.js');
const SC = require('../../js/shift-close.js');
const MB = require('../../tools/migration/ledger-baseline.js');
const { compatDb } = require('../support/compat-shim.js');

const ROOT = path.join(__dirname, '../..');
const E = c => `${c.toLowerCase()}@prodv2.local`;
const pad = n => String(n).padStart(2, '0');
const bkk = n => { const d = new Date(Date.now() + 7 * 3600000 - n * 86400000); return `${d.getUTCFullYear()}-${pad(d.getUTCMonth() + 1)}-${pad(d.getUTCDate())}`; };
let env, rnd = 12345;
const rand = () => (rnd = (rnd * 1103515245 + 12345) % 2147483648) / 2147483648;
const report = [];

function synthetic() {
  const logs = [];
  let n = 0;
  for (let d = 55; d >= 10; d--) for (const line of ['A', 'B', 'C']) for (const shift of ['DAY', 'NIGHT']) {
    const k = Math.floor(rand() * 5);
    for (let i = 0; i < k; i++) logs.push({ id: `L${++n}`, date: bkk(d), line, shift, model: 'M' + (1 + Math.floor(rand() * 4)), defectType: ['Dent', 'Scratch', 'Bubble'][Math.floor(rand() * 3)], scrapQty: 1 + Math.floor(rand() * 9), remark: '', createdAt: 1 });
  }
  // records the target never counted: old Thai shift codes, Door In Door, malformed date
  for (let i = 0; i < 4; i++) logs.push({ id: `X${i}`, date: bkk(30), line: 'A', shift: 'เช้า', model: 'M', defectType: 'Dent', scrapQty: 2, remark: '', createdAt: 1 });
  logs.push({ id: 'X9', date: bkk(30), line: 'D', shift: 'DAY', model: 'M', defectType: 'Dent', scrapQty: 5, remark: '', createdAt: 1 });
  logs.push({ id: 'X8', date: '30/10/2026', line: 'B', shift: 'DAY', model: 'M', defectType: 'Dent', scrapQty: 1, remark: '', createdAt: 1 });
  return logs;
}
async function raw(fn) { let o; await env.withSecurityRulesDisabled(async ctx => { o = await fn(ctx.firestore()); }); return o; }
const allLogs = () => raw(async db => { const o = []; (await getDocs(collection(db, 'scrapLogs'))).forEach(d => o.push(Object.assign({ id: d.id }, d.data()))); return o.sort((a, b) => a.id < b.id ? -1 : 1); });
const hash = x => crypto.createHash('sha256').update(JSON.stringify(x)).digest('hex').slice(0, 16);
const perDay = logs => { const m = {}; logs.filter(l => ['A', 'B', 'C'].includes(l.line) && ['DAY', 'NIGHT'].includes(l.shift)).forEach(l => { m[l.date] = (m[l.date] || 0) + l.scrapQty; }); return m; };
function actor(code) { const db = compatDb(env.authenticatedContext('uid-' + code, { email: E(code) }).firestore()); return { db, opts: { email: E(code), serverTimestamp } }; }

let logs0, plan, applied, applied2, mism;
before(async () => {
  env = await initializeTestEnvironment({ projectId: 'demo-quality-dashboard', firestore: { rules: fs.readFileSync(path.join(ROOT, 'emulator/firestore.rules'), 'utf8'), host: '127.0.0.1', port: 8080 } });
  await env.clearFirestore();
  const data = synthetic();
  await raw(async db => {
    const u = (role, slots) => ({ role, active: true, displayName: role, slots, updatedAt: 1, updatedBy: E('admin') });
    await setDoc(doc(db, 'qdUsers', E('admin')), u('admin', []));
    await setDoc(doc(db, 'qdUsers', E('leaderA')), u('leader', ['A_DAY', 'A_NIGHT']));
    for (let i = 0; i < data.length; i += 400) { const b = writeBatch(db); data.slice(i, i + 400).forEach(l => { const { id, ...rest } = l; b.set(doc(db, 'scrapLogs', id), rest); }); await b.commit(); }
  });
  // one slot already went through the ledger before the migration (it must be skipped)
  const A = actor('admin');
  await Ledger.applyOps(A.db, [{ op: 'create', ref: A.db.collection('scrapLogs').doc('pre'), data: { date: bkk(20), line: 'C', shift: 'NIGHT', model: 'M', defectType: 'Dent', scrapQty: 4, remark: '', createdAt: 1 } }], A.opts);
  logs0 = await allLogs();
});
after(async () => {
  if (plan) {
    const t = plan.totals;
    const md = ['# Ledger Baseline Migration — Dry Run Report (generated)', '',
      'Generated by `tests/rules/migration.test.js` on **synthetic data in the Firebase Emulator** (no production data was read or written).', '',
      '| Item | Value |', '|---|---|',
      `| Scrap logs read | ${t.logs} (${t.qty} pcs) |`,
      `| Slots to create (baseline) | ${t.planned.slots} slots, ${t.planned.logs} logs, ${t.planned.qty} pcs |`,
      `| Slots skipped (already in the ledger) | ${t.skipped.slots} slots, ${t.skipped.logs} logs, ${t.skipped.qty} pcs |`,
      `| Logs excluded (not Door A/B/C × DAY/NIGHT, never counted by the target) | ${t.excluded.logs} logs, ${t.excluded.qty} pcs |`,
      `| Plan check (every log exactly once) | ${MB.verifyPlan(plan).length === 0 ? 'OK' : 'FAILED'} |`,
      `| Applied | created ${applied.created.length}, skipped ${applied.skipped.length}, failed ${applied.failed.length} |`,
      `| Re-run (idempotent) | created ${applied2.created.length}, skipped ${applied2.skipped.length}, failed ${applied2.failed.length} |`,
      `| Post-apply verification | ${mism.length} mismatches |`, '',
      '## Additional checks', '', ...report.map(r => '- ' + r), '',
      '## Excluded records', '', '| id | date | line | shift | qty | reason |', '|---|---|---|---|---|---|',
      ...plan.excluded.map(x => `| ${x.id} | ${x.date} | ${x.line} | ${x.shift} | ${x.scrapQty} | ${x.reason} |`)].join('\n');
    fs.mkdirSync(path.join(ROOT, 'docs/phase5/generated'), { recursive: true });
    fs.writeFileSync(path.join(ROOT, 'docs/phase5/generated/migration-dry-run.md'), md + '\n');
  }
  if (env) await env.cleanup();
});

describe('baseline migration on synthetic data (emulator)', () => {
  it('dry run: the plan accounts for every log exactly once and writes nothing', async () => {
    const existing = await raw(async db => { const o = []; (await getDocs(collection(db, 'scrapSlots'))).forEach(d => o.push(d.id)); return o; });
    plan = MB.planBaseline(logs0, existing);
    assert.deepEqual(MB.verifyPlan(plan), []);
    assert.equal(plan.totals.excluded.logs, 6);
    assert.equal(plan.totals.skipped.slots, 1);
    assert.deepEqual((await allLogs()).map(l => l.id), logs0.map(l => l.id));
    assert.equal(await raw(async db => (await getDocs(collection(db, 'scrapSlots'))).size), 1);   // still only the pre-existing slot
  });
  it('apply as Admin: slots, audit event b1 and public mirror; scrap logs untouched; idempotent', async () => {
    const A = actor('admin');
    applied = await MB.applyBaseline(A.db, plan, Object.assign({ migrationId: 'mig-test-1' }, A.opts));
    assert.equal(applied.failed.length, 0, JSON.stringify(applied.failed.slice(0, 3)));
    assert.equal(applied.created.length, plan.slots.length);
    applied2 = await MB.applyBaseline(A.db, plan, Object.assign({ migrationId: 'mig-test-1' }, A.opts));
    assert.equal(applied2.created.length, 0); assert.equal(applied2.skipped.length, plan.slots.length);
    mism = await MB.verifyApplied(A.db, plan);
    assert.deepEqual(mism, []);
    const after = await allLogs();
    assert.equal(hash(after), hash(logs0), 'scrap logs byte-for-byte unchanged');
    assert.deepEqual(perDay(after), perDay(logs0));
    report.push(`Scrap logs before/after: SHA-256 ${hash(logs0)} / ${hash(after)} (identical); daily totals identical for ${Object.keys(perDay(after)).length} days.`);
    const s = plan.slots[0];
    const ev = await raw(async db => (await getDoc(doc(db, 'scrapSlots', s.slotId, 'events', 'b1'))).data());
    assert.equal(ev.type, 'BASELINE'); assert.equal(ev.legacyCount, s.count); assert.equal(ev.fingerprint, s.fingerprint);
    const sum = await raw(async db => (await getDoc(doc(db, 'scrapCloseSummary', s.date))).data());
    assert.equal(sum.slots[`${s.line}_${s.shift}`].liveLogCount, s.count);
  });
  it('after the baseline every slot is PENDING (no false CONFLICT) and the public mirror matches', async () => {
    const A = actor('admin');
    const counts = {};
    for (const s of plan.slots) { const st = (await SC.loadSlot(A.db, s.date, s.line, s.shift)).info.status; counts[st] = (counts[st] || 0) + 1; }
    assert.deepEqual(counts, { PENDING: plan.slots.length });
    report.push(`Status of the ${plan.slots.length} migrated slots after the baseline: ${JSON.stringify(counts)}.`);
  });
  it('only an Admin can create a baseline; a forged b1 is refused', async () => {
    const L = actor('leaderA');
    const fake = { slots: [{ slotId: `${bkk(60)}_A_DAY`, date: bkk(60), line: 'A', shift: 'DAY', count: 0, qty: 0, logIds: [], fingerprint: 'f' }] };
    const r = await MB.applyBaseline(L.db, fake, Object.assign({ migrationId: 'x' }, L.opts));
    assert.equal(r.failed.length, 1);
    const db = env.authenticatedContext('uid-admin', { email: E('admin') }).firestore(), id = `${bkk(61)}_A_DAY`;
    const b = writeBatch(db);
    b.set(doc(db, 'scrapSlots', id), { date: bkk(61), line: 'A', shift: 'DAY', logVersion: 0, liveLogCount: 3, legacyCount: 3, updatedAt: serverTimestamp(), updatedBy: E('admin') });
    b.set(doc(db, 'scrapSlots', id, 'events', 'b1'), { type: 'BASELINE', migrationId: 'x', legacyCount: 2, scrapQty: 1, logIds: ['a', 'b'], fingerprint: 'f', at: serverTimestamp(), by: E('admin') });
    b.set(doc(db, 'scrapCloseSummary', bkk(61)), { date: bkk(61), slots: { A_DAY: Ledger.publicView({ logVersion: 0, liveLogCount: 3 }) }, updatedAt: serverTimestamp() }, { merge: true });
    await assert.rejects(b.commit(), /permission/i);   // event count != slot legacyCount
  });
  it('after baselineComplete: a client cannot state legacyCount; stray logs around the ledger are caught', async () => {
    const A = actor('admin'), L = actor('leaderA');
    await MB.markComplete(A.db, 'mig-test-1', A.opts);
    // a record saved with sign-in "off" AFTER the migration, on a slot that has no ledger yet
    const day = bkk(3);
    await raw(async db => { await setDoc(doc(db, 'scrapLogs', 'stray1'), { date: day, line: 'A', shift: 'DAY', model: 'M', defectType: 'Dent', scrapQty: 2, remark: '', createdAt: 1 }); });
    // the ledger would need legacyCount 1 for that slot → refused: the stray record is surfaced, not absorbed
    await assert.rejects(Ledger.applyOps(L.db, [{ op: 'create', ref: L.db.collection('scrapLogs').doc(), data: { date: day, line: 'A', shift: 'DAY', model: 'M', defectType: 'Dent', scrapQty: 1, remark: '', createdAt: 1 } }], L.opts), /permission/i);
    await assert.rejects(SC.closeSlot(L.db, { date: day, line: 'A', shift: 'DAY', state: 'SUBMITTED' }, L.opts), /permission/i);
    // a slot with no old records still works normally
    await Ledger.applyOps(L.db, [{ op: 'create', ref: L.db.collection('scrapLogs').doc(), data: { date: day, line: 'A', shift: 'NIGHT', model: 'M', defectType: 'Dent', scrapQty: 1, remark: '', createdAt: 1 } }], L.opts);
    // a stray record on a migrated slot → CONFLICT
    const s = plan.slots.find(x => x.line === 'A');
    await raw(async db => { await setDoc(doc(db, 'scrapLogs', 'stray2'), { date: s.date, line: s.line, shift: s.shift, model: 'M', defectType: 'Dent', scrapQty: 2, remark: '', createdAt: 1 }); });
    assert.equal((await SC.loadSlot(A.db, s.date, s.line, s.shift)).info.status, 'CONFLICT');
    // recovery for the stray slot: Admin baselines it (audited), then it is a normal ledger slot
    const fix = MB.planBaseline((await allLogs()).filter(l => l.date === day && l.line === 'A' && l.shift === 'DAY'), []);
    const r = await MB.applyBaseline(A.db, fix, Object.assign({ migrationId: 'mig-fix-1' }, A.opts));
    assert.equal(r.created.length, 1);
    await SC.closeSlot(L.db, { date: day, line: 'A', shift: 'DAY', state: 'SUBMITTED' }, L.opts);
    report.push('After baselineComplete: a ledger write or close that would need legacyCount > 0 is refused (stray "off"-mode record surfaced); a stray record on a migrated slot shows CONFLICT; Admin re-baselines a stray slot (audited b1), after which it closes normally.');
  });
  it('qdConfig/ledger: only an Admin can set it', async () => {
    const L = actor('leaderA');
    await assert.rejects(MB.markComplete(L.db, 'x', L.opts), /permission/i);
  });
});
