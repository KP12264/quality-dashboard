// Builds emulator/firestore.rules.bridge = the combined candidate (emulator/firestore.rules)
// + the production snapshot's public Quality Dashboard blocks, copied unchanged.
// The bridge is a TRANSITION rules set: the new sign-in site works with it AND pages still in
// sign-in "off" keep saving exactly as today, so there is no write-failure window. It is as open
// as production is today (public write on the QD collections) — never the final state.
//   node tools/rules/build-bridge.js           write the file
//   node tools/rules/build-bridge.js --check   exit 1 when the file is out of date
// Emulator only. Nothing is published.
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '../..');

function build() {
  const cand = fs.readFileSync(path.join(ROOT, 'emulator/firestore.rules'), 'utf8');
  const prod = fs.readFileSync(path.join(ROOT, 'emulator/production.firestore.rules.snapshot'), 'utf8');
  const qdStart = prod.indexOf('    // ── Quality Dashboard (separate app');
  const qdEnd = prod.indexOf('    // ── Everything else');
  if (qdStart < 0 || qdEnd < qdStart) throw new Error('production snapshot: Quality Dashboard block not found');
  const publicBlock = prod.slice(qdStart, qdEnd).replace(/\s+$/, '') + '\n';
  const marker = '    // ── Everything else — default deny.';
  const at = cand.indexOf(marker);
  if (at < 0 || cand.indexOf(marker, at + 1) >= 0) throw new Error('candidate: default-deny marker not found exactly once');
  const header = '// BRIDGE RULES (generated by tools/rules/build-bridge.js — do not edit). TRANSITION ONLY:\n'
    + '// the candidate below + the production snapshot\'s public Quality Dashboard blocks (unchanged),\n'
    + '// so pages still in sign-in "off" keep working while the new site rolls out. Emulator only.\n';
  const body = cand.slice(0, at)
    + '    // ===== BEGIN bridge: copied unchanged from emulator/production.firestore.rules.snapshot =====\n'
    + publicBlock
    + '    // ===== END bridge =====\n\n'
    + cand.slice(at);
  return body.replace("rules_version = '2';\n", "rules_version = '2';\n" + header);
}
if (require.main === module) {
  const out = build();
  const file = path.join(ROOT, 'emulator/firestore.rules.bridge');
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
    if (cur !== out) { console.error('emulator/firestore.rules.bridge is out of date: run node tools/rules/build-bridge.js'); process.exit(1); }
    console.log('bridge rules up to date');
  } else { fs.writeFileSync(file, out); console.log('wrote emulator/firestore.rules.bridge'); }
}
module.exports = { build };
